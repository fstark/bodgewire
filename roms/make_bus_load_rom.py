#!/usr/bin/env python3
"""Writes roms/bus_load.rom, the 2716 of netlists/bus_load.bwn (docs/p5a-bus-load/BUS_LOAD_DESIGN.md).

0x000-0x5FF: code-like bytes from a fixed xorshift, so the data bus toggles on ROM fetches.
0x600-0x7FF: 64 glyphs x 8 lines, 8 dots wide, leftmost = O7: each 5-dot line of roms/2513.rom in
columns 1-5. Run from the repository root: python3 roms/make_bus_load_rom.py
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
CODE_BYTES = 0x600
SEED = 0x2545F491


def glyph_rows():
    rows = []
    for line in (ROOT / "2513.rom").read_text().splitlines():
        token = line.split(";", 1)[0].strip()
        if token and token[0] in ".#":
            rows.append(token)
    if len(rows) != 64 * 8 or any(len(r) != 5 for r in rows):
        raise SystemExit("2513.rom: expected 512 dot rows of 5")
    return rows


def code_bytes():
    state = SEED
    out = []
    for _ in range(CODE_BYTES):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        out.append(state & 0xFF)
    return out


def main():
    lines = [
        "; Bus load spike ROM (2716), docs/p5a-bus-load/BUS_LOAD_DESIGN.md. Generated by",
        "; roms/make_bus_load_rom.py from roms/2513.rom: do not edit, rerun the script.",
        "; 0x000-0x5FF code-like bytes; 0x600-0x7FF 64 glyphs x 8 lines, address 0x600 + code x 8 +",
        "; line, leftmost dot = O7, the 2513's five dots in columns 1-5.",
        "",
        "@000",
    ]
    data = code_bytes()
    for i in range(0, len(data), 16):
        lines.append(" ".join(f"{b:02X}" for b in data[i : i + 16]))
    lines += ["", "@600"]
    rows = glyph_rows()
    for code in range(64):
        lines.append(f"; 0x{code:02X}")
        for row in rows[code * 8 : code * 8 + 8]:
            lines.append("." + row + "..")
    (ROOT / "bus_load.rom").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
