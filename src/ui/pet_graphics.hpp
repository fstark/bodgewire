// The graphic on a key with this legend, or null (the words: RETURN, SHIFT, CRSR...). A key types
// its character c; SHIFT sets bit 7, which the screen shows as code c (c >= 0x40: letters, @ [ ]
// and the arrows) or c + 0x40 (the digits and symbols).
inline const std::array<std::uint8_t, 8>* PetGraphicOf(std::string_view legend) {
    if (legend.size() != 1) {
        return nullptr;
    }
    const auto c = static_cast<unsigned char>(legend[0]);
    if (c < 0x21 || c > 0x5F) {
        return nullptr;
    }
    return &kPetGraphics[(c >= 0x40 ? c : c + 0x40) - 0x40];
}

